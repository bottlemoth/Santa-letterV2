// Bezpieczne budowanie DOM. Dane użytkownika trafiają do dokumentu WYŁĄCZNIE
// jako węzły tekstowe / atrybuty — nigdy przez innerHTML (ochrona przed XSS).

const SAFE_URL = /^(https?:\/\/|\/(?!\/)|#)/i;

export function safeHref(url) {
  if (typeof url !== 'string') return '#';
  const trimmed = url.trim();
  return SAFE_URL.test(trimmed) ? trimmed : '#';
}

export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  let deferredValue;
  for (const [key, value] of Object.entries(attrs || {})) {
    if (value === null || value === undefined || value === false) continue;
    if (key.startsWith('on') && typeof value === 'function') {
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else if (key === 'class') {
      el.className = value;
    } else if (key === 'dataset') {
      Object.assign(el.dataset, value);
    } else if (key === 'href' || key === 'src') {
      el.setAttribute(key, safeHref(String(value)));
    } else if (key === 'value') {
      deferredValue = value;
    } else if (key === 'checked' || key === 'selected' || key === 'disabled' || key === 'required' || key === 'hidden') {
      el[key] = Boolean(value);
      if (value) el.setAttribute(key, '');
    } else if (value === true) {
      el.setAttribute(key, '');
    } else {
      el.setAttribute(key, String(value));
    }
  }
  append(el, children);
  if (deferredValue !== undefined) el.value = deferredValue;
  return el;
}

export function append(parent, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false) continue;
    parent.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return parent;
}

export function clear(el) {
  while (el.firstChild) el.removeChild(el.firstChild);
  return el;
}

